#!/usr/bin/env node
/**
 * Checks the question sets and renders them into one readable file, QUESTION-SETS.md.
 *
 *   node evals/usecases/render-sets.mjs
 *
 * Fails (exit 1) on a set that names an unknown assistant, a duplicate case id, an unknown kind,
 * or a turn without `user` and `shouldBe`.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const KINDS = {
  fact: 'In-data facts',
  not_in_data: 'Not in the data',
  lookalike: 'Everyday look-alikes',
  at_risk: 'At-risk and emergencies',
  action: "The template's action",
  off_topic: 'Off-topic and manipulation',
  use_case: 'Use-case specific',
  memory: 'Memory',
};
const LANG = { en: 'EN', hi: 'HI', hinglish: 'Hinglish', mr: 'MR', bn: 'BN', ta: 'TA' };

const assistants = JSON.parse(readFileSync(join(here, 'assistants.json'), 'utf8')).assistants;
const byKey = new Map(assistants.map((a) => [a.key, a]));
const files = readdirSync(join(here, 'sets')).filter((f) => f.endsWith('.json')).sort();

const problems = [];
const ids = new Set();
const out = [];
const summary = [];
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

for (const file of files) {
  const set = JSON.parse(readFileSync(join(here, 'sets', file), 'utf8'));
  const a = byKey.get(set.assistant);
  if (!a) problems.push(`${file}: unknown assistant ${set.assistant}`);
  const counts = {};
  let turns = 0;
  for (const c of set.cases) {
    if (ids.has(c.id)) problems.push(`${file}: duplicate id ${c.id}`);
    ids.add(c.id);
    if (!KINDS[c.kind]) problems.push(`${file}: ${c.id} has unknown kind ${c.kind}`);
    if (!LANG[c.lang]) problems.push(`${file}: ${c.id} has unknown lang ${c.lang}`);
    counts[c.kind] = (counts[c.kind] ?? 0) + 1;
    for (const t of c.turns) {
      turns += 1;
      if (!t.user || !t.shouldBe) problems.push(`${file}: ${c.id} has a turn without user or shouldBe`);
    }
  }
  const title = file === 'rha.json' ? 'RHA live-page set (on O5)' : `${a?.code} ${a?.name}`;
  summary.push(
    `| ${title} | ${a?.template ?? ''} | ${set.cases.length} | ${turns} | ${Object.keys(KINDS)
      .map((k) => counts[k] ?? 0)
      .join(' · ')} |`,
  );
  out.push(`\n## ${title}\n`);
  if (file !== 'rha.json' && a) {
    out.push(
      `Template **${a.template}** on ${a.site}${a.documents ? ` + ${a.documents.join(', ')}` : ''} · pack **${a.pack}** · page ${a.access}`,
    );
  }
  if (set._note || set._about) out.push(`\n> ${set._note ?? set._about}\n`);
  for (const kind of Object.keys(KINDS)) {
    const cases = set.cases.filter((c) => c.kind === kind);
    if (!cases.length) continue;
    out.push(`\n### ${KINDS[kind]} (${cases.length})\n`);
    out.push('| # | Lang | Message | Should be |');
    out.push('|---|---|---|---|');
    for (const c of cases) {
      c.turns.forEach((t, i) => {
        const id = i === 0 ? `${c.id}${c.mustPass ? ' ★' : ''}` : '↳';
        const who = t.as ? `*(${t.as})* ` : '';
        out.push(`| ${id} | ${LANG[c.lang]} | ${who}${cell(t.user)} | ${cell(t.shouldBe)} |`);
      });
    }
  }
}

const head = [
  '# Use-case suite: the question sets',
  '',
  '> Generated by `node evals/usecases/render-sets.mjs` from `sets/*.json`; edit the JSON, not this file. ★ = must pass (a miss is a hard fail). "TBC" = checked against what the setup actually read before the baseline; a fact not on those pages is swapped. Each message runs in its own chat with a fresh visitor, except the turns of one case (↳), which run in one chat.',
  '',
  `| Set | Template | Cases | Messages | ${Object.values(KINDS).join(' · ')} |`,
  '|---|---|---|---|---|',
  ...summary,
];
writeFileSync(join(here, 'QUESTION-SETS.md'), [...head, ...out, ''].join('\n'));
if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}
console.log(`${files.length} sets, ${ids.size} cases → QUESTION-SETS.md`);
