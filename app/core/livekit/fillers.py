"""Thinking-filler phrases for masking turn latency.

When a turn's voice-to-voice latency is high, the agent can play a short
back-channel ("Mm-hmm.", "Right...") the instant the user stops speaking, while
the real reply is still being generated by the graph. This does NOT reduce the
measured ``response_latency_ms`` (which still tracks the real reply) — it masks
the *perceived* gap so practice sessions feel responsive.

Two principles drive the defaults here:
  - **Language-aware:** scenarios are multilingual, so an English filler in a
    Tamil scenario would be jarring. We key defaults by the primary BCP-47
    subtag (``en-IN`` -> ``en``).
  - **Safe fallback:** for any language without a curated set, we fall back to
    non-lexical vocalizations ("Mm.", "Hmm...") which read as natural thinking
    sounds across languages and can't be "wrong".

Studio toggles the feature per scenario (``fillerEnabled``); the phrases
themselves are the purpose-built, language-aware back-channels defined below —
deliberately NOT the scenario's ``allowed_fillers`` (those are in-speech
discourse particles like "um"/"yaar" that read oddly as standalone thinking
sounds). A global kill-switch (``settings.FILLER_GLOBALLY_ENABLED``) lets ops
disable it platform-wide without a scenario edit.
"""

from __future__ import annotations

from typing import List, Optional

from app.core.config import settings
from app.core.logger import get_logger

logger = get_logger(__name__)

# Non-lexical thinking sounds — understood across languages, used as the
# fallback for any language without a curated set below.
NEUTRAL_FILLERS: List[str] = ["Mm.", "Mm-hmm.", "Hmm..."]

# Curated short back-channels per primary language subtag. Kept deliberately
# small and neutral (acknowledgement, not commitment) so they fit before any
# reply. Languages not listed fall back to NEUTRAL_FILLERS.
DEFAULT_FILLERS: dict[str, List[str]] = {
    "en": ["Mm-hmm.", "Right.", "Okay...", "I see.", "Hmm..."],
    "hi": ["हम्म...", "अच्छा...", "ठीक है...", "हाँ..."],
    "ta": ["ம்ம்...", "சரி...", "ஆமாம்...", "புரிகிறது..."],
}


def _scenario_language_code(scenario) -> Optional[str]:
    """Best-effort extract of the scenario's BCP-47 language code."""
    return getattr(
        getattr(scenario, "language_config", None), "language_code", None
    )


def resolve_filler_phrases(scenario) -> List[str]:
    """Resolve the filler phrases to use for ``scenario``.

    Returns an empty list when fillers are disabled (globally, or for this
    scenario), which the caller treats as "don't play a filler".

    Precedence: global kill-switch -> per-scenario ``filler_enabled`` ->
    language defaults (keyed by scenario language) -> neutral fallback.
    """
    if not getattr(settings, "FILLER_GLOBALLY_ENABLED", True):
        return []

    prompt_data = getattr(scenario, "prompt_data", None)
    if prompt_data is None:
        return []

    if not getattr(prompt_data, "filler_enabled", False):
        return []

    language_code = _scenario_language_code(scenario) or ""
    primary = language_code.split("-")[0].lower()
    phrases = DEFAULT_FILLERS.get(primary, NEUTRAL_FILLERS)
    logger.debug(
        "[FILLER] resolved %d default phrases for language=%s (primary=%s)",
        len(phrases),
        language_code or "unknown",
        primary or "none",
    )
    return phrases
