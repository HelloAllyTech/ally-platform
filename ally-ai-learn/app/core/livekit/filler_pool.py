"""The per-session pool of filler clips, and the rules for choosing one.

WHY THIS EXISTS
---------------
The predictive job used to REPLACE its batch of five phrases every cycle and
delete the previous set. With an anti-repeat memory capped at three, a long
session cycled through a handful of lines — each one the same recording every
time — which is exactly what makes a character sound like a soundboard rather
than a person thinking.

This pool instead ACCUMULATES: every accepted phrase stays available for the rest
of the session, tagged with its type, its duration tier and the turn it last
played on. Selection then has enough to work with to satisfy three rules at once:

1. **Fit the gap.** Prefer a clip whose length lands just under the predicted
   wait, so the filler finishes about when the real reply starts instead of
   trailing dead air.
2. **Don't repeat.** Never a phrase heard in the last few turns while an
   alternative exists, and never the identical waveform twice (variants of one
   phrase are distinct renderings — see ``filler_clips``).
3. **Vary the kind.** Never the same filler *type* twice in a row when another
   type is available, so a hesitation is followed by an acknowledgement rather
   than another hum.

The rules degrade rather than fail: with one clip in the pool it necessarily
repeats, and every constraint is dropped in priority order before the pool is
allowed to return nothing.
"""

from __future__ import annotations

import random
from typing import Dict, Iterable, List, Optional, Tuple

from app.core.livekit.filler_clips import TIERS, FillerClip
from app.core.logger import get_logger

logger = get_logger(__name__)


class FillerPool:
    """Accumulating, de-duplicated set of clips with recency-aware selection."""

    def __init__(self, max_clips: int = 40, repeat_window_plays: int = 12) -> None:
        self._clips: Dict[Tuple[str, int], FillerClip] = {}
        self._max_clips = max(1, max_clips)
        self._repeat_window = max(0, repeat_window_plays)
        self._turn = 0
        self._last_type: Optional[str] = None

    # ---- population -------------------------------------------------

    def add(self, clips: Iterable[FillerClip]) -> int:
        """Add clips, ignoring ones already present. Returns how many were new.

        De-duplication is on (phrase text, variant), so a phrase regenerated by a
        later batch doesn't displace the copy already in the pool — and a second
        RENDERING of the same phrase is a distinct entry, which is the point.

        When the pool is full the least recently *played* clips are evicted
        first, so the lines a session actually uses survive and stale ones from
        early batches make way. Clips never played (last_played_turn = -1) sort
        oldest, which is correct: an unused clip is the cheapest thing to lose.
        """
        added = 0
        for clip in clips or []:
            if not isinstance(clip, FillerClip) or not clip.phrase.strip():
                continue
            if clip.key in self._clips:
                continue
            self._clips[clip.key] = clip
            added += 1
        self._evict()
        return added

    def _evict(self) -> None:
        if len(self._clips) <= self._max_clips:
            return
        ordered = sorted(self._clips.values(), key=lambda c: c.last_played_turn)
        for clip in ordered[: len(self._clips) - self._max_clips]:
            self._clips.pop(clip.key, None)

    # ---- inspection -------------------------------------------------

    def __len__(self) -> int:
        return len(self._clips)

    @property
    def phrases(self) -> List[str]:
        """Distinct phrase texts currently held, for the prompt's do-not-repeat list."""
        seen: List[str] = []
        lowered = set()
        for clip in self._clips.values():
            key = clip.phrase.strip().lower()
            if key not in lowered:
                lowered.add(key)
                seen.append(clip.phrase)
        return seen

    def _is_fresh(self, clip: FillerClip) -> bool:
        """Whether ``clip`` may be used now without sounding like a repeat.

        A clip NEVER played is always fresh — it is the freshest thing in the
        pool. Comparing its sentinel ``-1`` against the recency cutoff directly
        would call an unheard clip stale for the first few turns of a session,
        which is exactly backwards and would make the pool ask for new phrases
        while a full unused batch sat there.

        The window is counted in PLAYS, not conversational turns, because a turn
        can play two fillers (the continuation). A window of N plays therefore
        covers roughly N/2 turns in the worst case — which is why the default is
        set in plays rather than turns, and why reading it as "turns" would make
        the anti-repeat guard half as wide as intended.
        """
        if clip.last_played_turn < 0:
            return True
        return clip.last_played_turn < self._turn - self._repeat_window

    def fresh_count(self) -> int:
        """Distinct PHRASES usable right now without repeating a recent one.

        The regeneration trigger uses this to skip an LLM call while the pool
        still has enough unheard material, which is most of the time in a short
        session.

        Counted in distinct phrases, not clips, and that distinction matters: a
        second RENDERING of a line is a separate clip but the same words. Count
        clips and the variants quietly satisfy the freshness threshold, so the
        pool stops asking for genuinely new lines and the session ends up
        cycling the same few phrases in alternate takes — the exact failure the
        pool exists to prevent.
        """
        return len(
            {
                c.phrase.strip().lower()
                for c in self._clips.values()
                if self._is_fresh(c)
            }
        )

    def variant_needed(self) -> List[Tuple[str, str, int]]:
        """Phrases played at least once that have only one rendering so far.

        Returns ``(phrase, filler_type, next_variant)`` triples for the caller to
        synthesize, so the second time a line is used it is a different take
        rather than the same audio again.
        """
        by_phrase: Dict[str, List[FillerClip]] = {}
        for clip in self._clips.values():
            by_phrase.setdefault(clip.phrase.strip().lower(), []).append(clip)
        out: List[Tuple[str, str, int]] = []
        for clips in by_phrase.values():
            if len(clips) > 1:
                continue
            clip = clips[0]
            if clip.last_played_turn >= 0:
                out.append((clip.phrase, clip.filler_type, clip.variant + 1))
        return out

    # ---- selection --------------------------------------------------

    def _tier_order(self, target_ms: Optional[float]) -> List[str]:
        """Tier names ranked by how well they fit ``target_ms``.

        The best tier is the one containing the target; the rest follow by
        distance, with SHORTER tiers preferred over longer at equal distance —
        overshooting means the reply cuts the filler off mid-word, which is worse
        than a small gap.
        """
        names = [name for name, _, _ in TIERS]
        if target_ms is None:
            return names

        def score(entry: Tuple[str, float, float]) -> Tuple[float, float]:
            _, low, high = entry
            if low <= target_ms < high:
                return (0.0, low)
            if target_ms >= high:
                return (target_ms - high, low)
            return (low - target_ms + 1.0, low)  # +1: penalise overshoot

        return [name for name, _, _ in sorted(TIERS, key=score)]

    def choose(
        self,
        target_ms: Optional[float] = None,
        rng: Optional[random.Random] = None,
    ) -> Optional[FillerClip]:
        """Pick the clip to play now, or None when the pool is empty.

        Filters are applied hardest-first and relaxed one at a time, so a small
        pool still returns something rather than nothing:
        tier fit -> not recently played -> different type from the last one.

        Pairs with ``mark_played``: choosing does not itself advance the pool's
        recency state, so a caller that plays a clip MUST mark it, or the next
        call will legitimately return the same clip again.
        """
        if not self._clips:
            return None
        chooser = rng or random
        everything = list(self._clips.values())

        not_recent = [c for c in everything if self._is_fresh(c)]
        candidates = not_recent or everything

        different_type = [
            c
            for c in candidates
            if self._last_type is None or c.filler_type != self._last_type
        ]
        candidates = different_type or candidates

        for tier in self._tier_order(target_ms):
            in_tier = [c for c in candidates if c.tier == tier]
            if in_tier:
                candidates = in_tier
                break

        # Among equally eligible clips prefer the one heard longest ago, breaking
        # ties randomly so the rotation doesn't become a fixed cycle.
        oldest = min(c.last_played_turn for c in candidates)
        return chooser.choice([c for c in candidates if c.last_played_turn == oldest])

    def mark_played(self, clip: FillerClip) -> None:
        """Record that ``clip`` was played, advancing the turn counter."""
        self._turn += 1
        clip.last_played_turn = self._turn
        self._last_type = clip.filler_type

    def age_turns(self, clip: FillerClip) -> int:
        """How many turns ago ``clip`` last played; -1 if never before now."""
        return -1 if clip.last_played_turn < 0 else self._turn - clip.last_played_turn
