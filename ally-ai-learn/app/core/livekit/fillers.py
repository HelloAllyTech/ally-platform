"""Thinking-filler phrases for masking turn latency.

When a turn's voice-to-voice latency is high, the agent can play a short
back-channel the instant the user stops speaking, while the real reply is still
being generated by the graph. The filler IS the agent's first words, so it
counts as first-audio for ``response_latency_ms`` (see
app/core/metrics/turn_metrics.py); the unmasked time to the real reply is kept
alongside it as ``metadata.replyLatencyMs``.

The live agent prefers LLM-generated PREDICTIVE fillers (see
app/core/livekit/predictive_filler.py); resolve_filler_phrases below only
provides the STATIC fallback used until the first predictive batch is ready.

Static phrase source, in precedence order (resolve_filler_phrases):
  1. **Scenario ``allowed_fillers``** — the per-language filler words authored
     in Studio (``allowedFillerWords``, flattened by Core to the active
     language). Authored in the correct native script.
  2. Otherwise **no static filler**. There is intentionally no hardcoded
     fallback: the phrases must come from Studio so they're always in the right
     language / script (the Indic TTS spells Latin text out letter-by-letter,
     "Mm" -> "M M"). A scenario with none configured plays no static filler
     (predictive fillers may still play once generated).

Studio toggles the feature per scenario (``fillerEnabled``) and a global
kill-switch (``settings.FILLER_GLOBALLY_ENABLED``) lets ops disable it
platform-wide without a scenario edit.
"""

from __future__ import annotations

from typing import List, Optional

from app.core.config import settings
from app.core.logger import get_logger

logger = get_logger(__name__)


def _scenario_language_code(scenario) -> Optional[str]:
    """Best-effort extract of the scenario's BCP-47 language code."""
    return getattr(getattr(scenario, "language_config", None), "language_code", None)


def is_filler_enabled(scenario) -> bool:
    """Whether the thinking-filler feature is on for this session.

    This is the gate independent of whether any static phrases are configured:
    the global kill-switch AND the per-scenario ``filler_enabled`` toggle (the
    email allowlist is enforced upstream by Core, which strips filler config
    from the room metadata for non-allowlisted users, so ``filler_enabled``
    already arrives False for them). Used to decide whether the predictive
    (LLM-generated) filler layer may run even when no static phrases exist.
    """
    if not getattr(settings, "FILLER_GLOBALLY_ENABLED", True):
        return False
    prompt_data = getattr(scenario, "prompt_data", None)
    if prompt_data is None:
        return False
    return bool(getattr(prompt_data, "filler_enabled", False))


def resolve_filler_phrases(scenario) -> List[str]:
    """Resolve the filler phrases to use for ``scenario``.

    Returns an empty list when fillers are disabled (globally, or for this
    scenario) or when no phrases are configured — the caller treats an empty
    list as "don't play a filler".

    These are the STATIC fallback phrases only; the live agent prefers
    LLM-generated predictive fillers and uses this set as the fallback.
    Precedence: global kill-switch -> per-scenario ``filler_enabled`` ->
    ``allowed_fillers`` (Studio per-language filler words) -> [] (no filler).
    """
    if not getattr(settings, "FILLER_GLOBALLY_ENABLED", True):
        return []

    prompt_data = getattr(scenario, "prompt_data", None)
    if prompt_data is None:
        return []

    if not getattr(prompt_data, "filler_enabled", False):
        return []

    language_code = _scenario_language_code(scenario) or "unknown"

    # Studio-authored per-language filler words (static fallback for the live
    # agent, which prefers LLM-generated predictive fillers).
    allowed = getattr(prompt_data, "allowed_fillers", None)
    if allowed:
        cleaned = [p.strip() for p in allowed if isinstance(p, str) and p.strip()]
        if cleaned:
            logger.debug(
                "[FILLER] using %d Studio allowed_fillers for language=%s",
                len(cleaned),
                language_code,
            )
            return cleaned

    # No static phrases configured for this scenario — skip the static fallback
    # (predictive fillers may still play once generated). No hardcoded fallback:
    # phrases must come from Studio so they're in the right language/script.
    logger.info(
        "[FILLER] no allowed_fillers for language=%s; no static filler",
        language_code,
    )
    return []
