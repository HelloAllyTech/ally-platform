"""Pydantic models for the scenario report generation feature."""

from enum import Enum
from typing import Any, Dict, List, Literal, Optional

from pydantic import BaseModel, Field


class ReportStatus(str, Enum):
    """Report generation status."""

    PROCESSING = "PROCESSING"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"
    # Set when user-initiated cancel propagated from ally-be lands while
    # the report is still running. Distinct from FAILED (no error) and
    # from in-conversation termination events (those still produce a
    # COMPLETED report with a partial transcript).
    CANCELLED = "CANCELLED"


class ScenarioReportRequest(BaseModel):
    """Request body for POST /api/v1/scenario-report/generate."""

    prompt: str = Field(
        ...,
        description="System prompt for the counselor simulation agent",
    )
    turns: int = Field(
        ...,
        ge=1,
        description="Number of conversation turns to simulate",
    )
    language: str = Field(
        ...,
        description="BCP 47 language code (e.g., 'en-US')",
    )
    scenario_id: int = Field(..., description="Scenario identifier")
    report_id: str = Field(..., description="Unique report identifier (UUID)")
    metadata: Dict[str, Any] = Field(
        ...,
        description=(
            "Full scenario metadata envelope " "(same format as LiveKit room metadata)"
        ),
    )
    evaluator_prompt_code: Optional[str] = Field(
        default=None,
        description=(
            "promptCode of the transcript-evaluator prompt variant to run. When "
            "set, the evaluator (LLM-judge) system prompt is resolved from this "
            "variant's (dashboard-overridden) text instead of the default "
            "evaluator template. Falls back to the default when unset or "
            "unresolvable."
        ),
    )


class ScenarioReportResponse(BaseModel):
    """Immediate response returned when report generation is accepted."""

    scenario_id: int
    report_id: str
    status: ReportStatus = ReportStatus.PROCESSING
    already_running: bool = Field(
        default=False,
        description=(
            "True when a report with this report_id was already queued or "
            "running in this worker, so this request started nothing new "
            "(e.g. a retried trigger). Its result still arrives by webhook."
        ),
    )


class TranscriptEntry(BaseModel):
    """Single transcript entry in the conversation."""

    content: str = Field(..., description="Message text content")
    start_time: float = Field(
        ...,
        description="Wall-clock start time in seconds from session start",
    )
    role: Literal["CLIENT", "COUNSELOR"] = Field(
        ..., description="Who sent this message"
    )


class ScenarioReportWebhookPayload(BaseModel):
    """Payload sent to the core backend webhook after report completion."""

    metrics: Dict[str, Any] = Field(
        ...,
        description=(
            "LLM-judge evaluation metrics: gradual_disclosure, difficulty_level, "
            "colloquialism, context_appropriateness, consistency, resistance"
        ),
    )
    status: ReportStatus = Field(..., description="Report completion status")
    transcripts: List[TranscriptEntry] = Field(
        ..., description="Full conversation transcript"
    )
    report_markdown: str = Field(
        default="",
        description="Full markdown evaluation report generated by the LLM judge",
    )
    error_message: Optional[str] = Field(
        default=None,
        description=(
            "Human-readable failure reason. Only populated when status=FAILED. "
            "Truncated to ~500 chars at call site to fit DB row sanely."
        ),
    )
