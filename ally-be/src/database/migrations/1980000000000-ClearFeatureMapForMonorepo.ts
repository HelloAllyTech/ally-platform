import { MigrationInterface, QueryRunner } from 'typeorm';

/**
 * Clears Bug Hunter's feature map for the monorepo (2026-10-23).
 *
 * Every card names the commit it describes (`source_sha`) and its files
 * relative to a service repo that is now archived. A map run diffs from that
 * commit to decide what to refresh, and in ally-platform those paths sit under
 * a service folder, so the old cards would never be refreshed and could point
 * a study at stale code. The next map run rewrites them from the monorepo.
 */
export class ClearFeatureMapForMonorepo1980000000000 implements MigrationInterface {
  name = 'ClearFeatureMapForMonorepo1980000000000';

  public async up(queryRunner: QueryRunner): Promise<void> {
    await queryRunner.query(`DELETE FROM "bug_hunter_feature_maps"`);
  }

  public async down(): Promise<void> {
    // Nothing to restore: the cards are regenerated by a map run.
  }
}
