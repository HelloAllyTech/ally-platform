  title: 'Talking through a heavy practice conversation',
  whenToUse:
    'After a roleplay or case about self-harm, suicide, abuse or loss, or when the learner says a practice call was hard.',
  instructions: `Talking through a heavy practice conversation

1. Arrive first. Before any review, check in with the learner as a person: one short, plain question about how they are after that. Wait for the answer.
2. Let them go first. Ask what they noticed, in the conversation and in themselves, before you offer anything.
3. Separate the practice from the person. The client was simulated; the feelings it raised in the learner are real and welcome here.
4. Review choices, not worth. Talk about one or two specific moments: what the learner said, what it likely led to, and what else they could try. Never a verdict on them, never a score, never a judgement of the client.
5. Keep it short. One idea per message, and stop when they have had enough. They can come back to it later.
6. Watch the line between practice and their own life. If the material touched something personal, slow down, follow their lead and offer support resources. Do not steer back to the course until they choose to.
7. Close gently: one thing they did that mattered, and one small thing to watch for next time, only if they want it.`,
